        Write-TestLog "Performance snapshot saved: $Type $(if($Label){"- $Label"})" "DEBUG" "PERF"
    }
}

function Get-PerformanceReport {
    <#
    .SYNOPSIS
    Generates a performance report from collected metrics.
    #>
    if (-not $Script:TestMetrics -or $Script:TestMetrics.ResourceSnapshots.Count -eq 0) {
        return $null
    }
    
    $snapshots = $Script:TestMetrics.ResourceSnapshots
    $totalDuration = (Get-Date) - $Script:TestMetrics.StartTime
    
    # Calculate resource usage statistics
    $cpuStats = $snapshots | Where-Object { $_.Resources.CPU } | ForEach-Object { $_.Resources.CPU }
    $memoryStats = $snapshots | Where-Object { $_.Resources.MemoryUsedPercent } | ForEach-Object { $_.Resources.MemoryUsedPercent }
    $diskStats = $snapshots | Where-Object { $_.Resources.DiskUsedPercent } | ForEach-Object { $_.Resources.DiskUsedPercent }
    
    return @{
        TotalDuration = $totalDuration
        SnapshotCount = $snapshots.Count
        CPU = @{
            Average = if ($cpuStats) { ($cpuStats | Measure-Object -Average).Average } else { 0 }
            Maximum = if ($cpuStats) { ($cpuStats | Measure-Object -Maximum).Maximum } else { 0 }
            Minimum = if ($cpuStats) { ($cpuStats | Measure-Object -Minimum).Minimum } else { 0 }
        }
        Memory = @{
            Average = if ($memoryStats) { ($memoryStats | Measure-Object -Average).Average } else { 0 }
            Maximum = if ($memoryStats) { ($memoryStats | Measure-Object -Maximum).Maximum } else { 0 }
            Minimum = if ($memoryStats) { ($memoryStats | Measure-Object -Minimum).Minimum } else { 0 }
        }
        Disk = @{
            Average = if ($diskStats) { ($diskStats | Measure-Object -Average).Average } else { 0 }
            Maximum = if ($diskStats) { ($diskStats | Measure-Object -Maximum).Maximum } else { 0 }
            Minimum = if ($diskStats) { ($diskStats | Measure-Object -Minimum).Minimum } else { 0 }
        }
        Snapshots = $snapshots
    }
}

