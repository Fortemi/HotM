        return $artifactInfo
    } else {
        Write-TestLog "Artifact not found: $Path" "WARN" "ARTIFACT"
        return $null
    }
}

function Get-InstallerVersion {
    <#
    .SYNOPSIS
    Extracts version information from the MSI installer.
    
    .PARAMETER InstallerPath
    Path to the MSI installer file.
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)]
        [string]$InstallerPath
    )
    
    if (-not (Test-Path $InstallerPath)) {
        throw "Installer not found: $InstallerPath"
    }
    
    try {
        # Use Windows Installer COM object to read MSI properties
        $windowsInstaller = New-Object -ComObject WindowsInstaller.Installer
        $database = $windowsInstaller.GetType().InvokeMember("OpenDatabase", "InvokeMethod", $null, $windowsInstaller, @($InstallerPath, 0))
        
        # Query for version information
        $query = "SELECT Value FROM Property WHERE Property = 'ProductVersion'"
        $view = $database.GetType().InvokeMember("OpenView", "InvokeMethod", $null, $database, $query)
        $view.GetType().InvokeMember("Execute", "InvokeMethod", $null, $view, $null)
        
        $record = $view.GetType().InvokeMember("Fetch", "InvokeMethod", $null, $view, $null)
        
        if ($record) {
            $version = $record.GetType().InvokeMember("StringData", "GetProperty", $null, $record, 1)
            return $version
        } else {
            throw "Could not read version from MSI"
        }
        
    } catch {
        Write-TestLog "Failed to read installer version: $($_.Exception.Message)" "WARN" "INSTALLER"
        return "Unknown"
    } finally {
        if ($view) { [System.Runtime.InteropServices.Marshal]::ReleaseComObject($view) | Out-Null }
        if ($database) { [System.Runtime.InteropServices.Marshal]::ReleaseComObject($database) | Out-Null }
        if ($windowsInstaller) { [System.Runtime.InteropServices.Marshal]::ReleaseComObject($windowsInstaller) | Out-Null }
    }
}

function Test-RegistryKey {
    <#
    .SYNOPSIS
    Tests if a registry key exists and optionally validates its value.
    
    .PARAMETER Path
    Registry path to test.
    
    .PARAMETER Name
    Registry value name to test.
    
    .PARAMETER ExpectedValue
    Expected value to validate against.
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)]
        [string]$Path,
        
        [Parameter(Mandatory = $false)]
        [string]$Name,
        
        [Parameter(Mandatory = $false)]
        [string]$ExpectedValue
    )
    
    try {
        if ($Name) {
            $value = Get-ItemProperty -Path $Path -Name $Name -ErrorAction Stop
            
            if ($ExpectedValue) {
                return ($value.$Name -eq $ExpectedValue)
            } else {
                return ($value.$Name -ne $null)
            }
        } else {
            $key = Get-Item -Path $Path -ErrorAction Stop
            return ($key -ne $null)
        }
    } catch {
        return $false
    }
}

function Initialize-PerformanceMonitoring {
    <#
    .SYNOPSIS
    Initializes performance monitoring for test execution.
    #>
    $Script:TestMetrics = @{
        StartTime = Get-Date
        ResourceSnapshots = @()
        PerformanceCounters = @{}
    }
    
    # Take initial resource snapshot
    $Script:TestMetrics.ResourceSnapshots += @{
